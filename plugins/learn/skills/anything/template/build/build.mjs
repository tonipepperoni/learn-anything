#!/usr/bin/env node
/*
 * build.mjs — assemble the study app's SQLite database from study.config.json
 * plus per-topic content (content/<NN-slug>/{guide.md,questions.json}).
 *
 * Emits everything the static web app needs, with zero network fetches:
 *   data/quiz.db          the SQLite database (also queryable with the sqlite3 CLI)
 *   data/quiz-db.js       the DB as base64 (window.__QUIZ_DB_B64)
 *   vendor/sql-wasm-b64.js  the sql.js wasm as base64 (window.__SQL_WASM_B64)
 *
 * Run from the project root:  node build/build.mjs
 * Requires Node >= 22 (uses the built-in node:sqlite). No npm install needed.
 */
import { marked } from './vendor/marked.esm.js';
import { DatabaseSync } from 'node:sqlite';
import { readFileSync, writeFileSync, existsSync, mkdirSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const __dirname = dirname(fileURLToPath(import.meta.url));
const ROOT = join(__dirname, '..');           // project root (template root)
const OUT_DIR = join(ROOT, 'data');
const OUT_DB = join(OUT_DIR, 'quiz.db');
const CONFIG = join(ROOT, 'study.config.json');
const HEADER = '// AUTO-GENERATED by build/build.mjs — do not edit by hand.\n';

function die(msg) { console.error('✗ ' + msg); process.exit(1); }
function pad2(n) { return String(n).padStart(2, '0'); }

// Replace <img src="x.svg"> (produced by marked) with the inlined, responsive SVG.
function inlineSvgs(html, dir) {
  return html.replace(/<img\b[^>]*>/g, function (tag) {
    var src = (tag.match(/\bsrc="([^"]+)"/) || [])[1] || '';
    var alt = (tag.match(/\balt="([^"]*)"/) || [])[1] || '';
    if (!/\.svg$/i.test(src)) return tag;
    var file = join(dir, src);
    if (!existsSync(file)) return '<figure class="diagram missing"><figcaption>' + alt + ' (diagram missing)</figcaption></figure>';
    var svg = readFileSync(file, 'utf8').replace(/<\?xml[^>]*\?>/g, '').replace(/<!DOCTYPE[^>]*>/gi, '').trim();
    // responsive: drop fixed width/height on the root <svg>, keep viewBox
    svg = svg.replace(/(<svg\b[^>]*?)\s+width="[^"]*"/i, '$1').replace(/(<svg\b[^>]*?)\s+height="[^"]*"/i, '$1');
    var cap = alt ? '<figcaption>' + alt + '</figcaption>' : '';
    return '<figure class="diagram">' + svg + cap + '</figure>';
  });
}

if (!existsSync(CONFIG)) die('study.config.json not found at project root.');
const cfg = JSON.parse(readFileSync(CONFIG, 'utf8'));

// ---- validate / normalize config ----
if (!cfg.title) die('config.title is required.');
if (!Array.isArray(cfg.domains) || !cfg.domains.length) die('config.domains must be a non-empty array.');
if (!Array.isArray(cfg.topics) || !cfg.topics.length) die('config.topics must be a non-empty array.');
if (!Array.isArray(cfg.levels) || cfg.levels.length < 2) die('config.levels must have at least 2 entries.');
if (!Array.isArray(cfg.badges)) cfg.badges = [];

const domainByName = {};
cfg.domains.forEach((d, i) => {
  if (!d.name) die('every domain needs a name.');
  d.index = i;
  d.weight = Number(d.weight) || 0;
  domainByName[d.name] = d;
});
// normalize levels: sort by xp, assign level numbers
cfg.levels.sort((a, b) => (a.xp || 0) - (b.xp || 0));
cfg.levels.forEach((l, i) => { l.lvl = i + 1; l.xp = Number(l.xp) || 0; });
cfg.masteryThreshold = Number(cfg.masteryThreshold) || 95;
cfg.exam = cfg.exam || {};
cfg.exam.questions = Number(cfg.exam.questions) || 30;
cfg.exam.minutes = Number(cfg.exam.minutes) || 45;
cfg.passMark = Number(cfg.passMark) || 72;

// ---- build DB ----
if (!existsSync(OUT_DIR)) mkdirSync(OUT_DIR, { recursive: true });
if (existsSync(OUT_DB)) { const { rmSync } = await import('node:fs'); rmSync(OUT_DB); }

const db = new DatabaseSync(OUT_DB);
db.exec(`
  PRAGMA journal_mode = MEMORY;
  CREATE TABLE app_config (id INTEGER PRIMARY KEY CHECK (id = 1), json TEXT NOT NULL);
  CREATE TABLE topics (
    id INTEGER PRIMARY KEY, slug TEXT NOT NULL, name TEXT NOT NULL,
    domain TEXT NOT NULL, domain_index INTEGER NOT NULL,
    domain_weight INTEGER NOT NULL, question_count INTEGER NOT NULL DEFAULT 0
  );
  CREATE TABLE questions (
    id INTEGER PRIMARY KEY, topic_id INTEGER NOT NULL, number INTEGER NOT NULL,
    text TEXT NOT NULL, correct TEXT NOT NULL, explanation TEXT
  );
  CREATE TABLE options (
    question_id INTEGER NOT NULL, letter TEXT NOT NULL, text TEXT NOT NULL,
    PRIMARY KEY (question_id, letter)
  );
  CREATE TABLE guides (topic_id INTEGER PRIMARY KEY, content TEXT);
  CREATE INDEX idx_questions_topic ON questions(topic_id);
`);

const insTopic = db.prepare('INSERT INTO topics (id,slug,name,domain,domain_index,domain_weight,question_count) VALUES (?,?,?,?,?,?,?)');
const insQ = db.prepare('INSERT INTO questions (id,topic_id,number,text,correct,explanation) VALUES (?,?,?,?,?,?)');
const insO = db.prepare('INSERT INTO options (question_id,letter,text) VALUES (?,?,?)');
const insG = db.prepare('INSERT INTO guides (topic_id,content) VALUES (?,?)');

const LETTERS = ['A', 'B', 'C', 'D', 'E', 'F'];
let qid = 0, totalQ = 0, totalGuides = 0;

db.exec('BEGIN');
for (const t of cfg.topics) {
  if (!t.id || !t.slug || !t.name || !t.domain) die('each topic needs id, slug, name, domain.');
  const dom = domainByName[t.domain];
  if (!dom) die(`topic "${t.name}" references unknown domain "${t.domain}".`);
  const folder = join(ROOT, 'content', pad2(t.id) + '-' + t.slug);

  // questions
  const qPath = join(folder, 'questions.json');
  let questions = [];
  if (existsSync(qPath)) {
    questions = JSON.parse(readFileSync(qPath, 'utf8'));
  } else {
    console.warn(`  ! no questions.json for ${t.name} (${folder})`);
  }
  let num = 0;
  for (const q of questions) {
    const opts = q.options || [];
    const ans = typeof q.answer === 'number' ? q.answer
      : LETTERS.indexOf(String(q.answer || '').toUpperCase());
    if (opts.length < 2 || ans < 0 || ans >= opts.length) {
      console.warn(`  ! skipping bad question in ${t.slug}: ${JSON.stringify(q).slice(0, 80)}`);
      continue;
    }
    qid++; num++;
    insQ.run(qid, t.id, num, String(q.question || q.q || ''), LETTERS[ans], String(q.explanation || ''));
    opts.forEach((text, i) => insO.run(qid, LETTERS[i], String(text)));
    totalQ++;
  }
  insTopic.run(t.id, t.slug, t.name, t.domain, dom.index, dom.weight, num);

  // guide (render markdown, inline any referenced SVG diagrams)
  const gPath = join(folder, 'guide.md');
  if (existsSync(gPath)) {
    let md = readFileSync(gPath, 'utf8').replace(/^\s*#\s+.*(\r?\n)+/, ''); // strip leading H1
    let html = inlineSvgs(marked.parse(md), folder);
    html = html.replace(/<p>\s*(<figure[\s\S]*?<\/figure>)\s*<\/p>/g, '$1'); // unwrap <p><figure></p>
    insG.run(t.id, html);
    totalGuides++;
  }
  console.log(`  ${pad2(t.id)}-${t.slug.padEnd(28)} ${num} questions${existsSync(gPath) ? ' + guide' : ''}`);
}

// store the whole config for the web app to consume
db.prepare('INSERT INTO app_config (id, json) VALUES (1, ?)').run(JSON.stringify(cfg));
db.exec('COMMIT');
db.close();

// ---- emit base64 bundles ----
const dbB64 = readFileSync(OUT_DB).toString('base64');
writeFileSync(join(OUT_DIR, 'quiz-db.js'), `${HEADER}window.__QUIZ_DB_B64 = "${dbB64}";\n`);

const wasmPath = join(ROOT, 'vendor', 'sql-wasm.wasm');
const wasmB64 = readFileSync(wasmPath).toString('base64');
writeFileSync(join(ROOT, 'vendor', 'sql-wasm-b64.js'), `${HEADER}window.__SQL_WASM_B64 = "${wasmB64}";\n`);

console.log(`\n✅ Built ${cfg.title}`);
console.log(`   ${cfg.topics.length} topics, ${totalQ} questions, ${totalGuides} guides`);
console.log(`   emitted data/quiz-db.js (${(dbB64.length / 1048576).toFixed(2)} MB) + vendor/sql-wasm-b64.js`);
if (totalQ === 0) console.log('\n   Note: no questions found — add content/<NN-slug>/questions.json files.');
